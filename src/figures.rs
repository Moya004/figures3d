static FIGURES: &[(&str, &Figure)] = &[
    ("cube", &CUBE),
    ("pyramid", &PYRAMID),
    ("tetrahedron", &TETRAHEDRON),
    ("dodecahedron", &DODECAHEDRON),
    ("icosahedron", &ICOSAHEDRON),
];

pub fn get_figure(name: &str) -> Option<&'static Figure> {
    FIGURES.iter().find(|(n, _)| *n == name).map(|(_, f)| *f)
}
